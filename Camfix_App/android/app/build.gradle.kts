// google_maps_flutter needs the Maps key in the manifest at build time.
// Put `MAPS_API_KEY=...` in android/local.properties (git-ignored); absent =
// the app uses the keyless OpenStreetMap map. See GOOGLE_MAPS_SETUP.md.
